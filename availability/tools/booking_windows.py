# Booking windows measured from each campground's Recreation.gov availability calendar -> data/windows.js
#   python3 -I tools/booking_windows.py <windows.json.jsonl from measure_windows.py> data/windows.js YYYY-MM-DD RELEASE-DAY
# RELEASE-DAY is the last day whose 7:00 AM Pacific release had happened when the calendars were read (e.g. 2026-11-08).
# A night shown "Available"/"Reserved" is open for booking; "NYR" is not yet released. Where the edge between the two
# is visible, the window is exact; where a closed season hides it, only a range is known and the 6-month default stays.
import json, sys, calendar, datetime as d
src, out, day, rel = sys.argv[1], sys.argv[2], sys.argv[3], d.date.fromisoformat(sys.argv[4])
def add_months(t, n):
    y, m = t.year + (t.month - 1 + n) // 12, (t.month - 1 + n) % 12 + 1
    return d.date(y, m, min(t.day, calendar.monthrange(y, m)[1]))
CAND = {n: add_months(rel, n) for n in (1, 2, 3, 4, 5, 6, 9, 12)}
fmt = lambda t: t.strftime("%m/%d/%Y")
res = {}
for line in open(src):
    x = json.loads(line); r = x["r"]; eid = x["id"]
    st = set(r.get("statuses") or [])
    L = d.date.fromisoformat(r["last_released"]) if r.get("last_released") else None
    F = d.date.fromisoformat(r["first_nyr"]) if r.get("first_nyr") else None
    w = None
    if not st:
        continue                                                    # no calendar: nothing measured
    if not (st & {"Available", "Reserved", "NYR", "Not Available Cutoff"}):
        w = {"fcfs": True, "note": "Every night is listed as not reservable on Recreation.gov"}
    elif L and F and (F - L).days == 1:
        n = next((n for n, t in CAND.items() if abs((L - t).days) <= 1), None)
        dd = (L - rel).days
        if n: w = {"months": n, "note": f"Open for booking through {fmt(L)}"}
        elif dd in (6, 7, 13, 14): w = {"days": dd + (1 if dd in (6, 13) else 0), "note": f"Open for booking through {fmt(L)}"}
        else: w = {"through": fmt(L), "note": f"Open for booking through {fmt(L)}; not a rolling window the site can model"}
    elif L and F:
        fits = [n for n, t in CAND.items() if L - d.timedelta(1) <= t <= F]
        if len(fits) == 1: w = {"months": fits[0], "note": f"Open through {fmt(L)}; not yet released from {fmt(F)}"}
        elif L > CAND[6] + d.timedelta(1): w = {"months": 6, "plus": True, "note": f"Open through {fmt(L)} (a little past 6 months); not yet released from {fmt(F)}"}
        else: w = {"range": fits, "note": f"Open through {fmt(L)}; not yet released from {fmt(F)}"}
    elif L and not F:
        if L >= CAND[9]: w = {"months": 12, "note": f"Already open for the whole season, through {fmt(L)}"}
        elif L > CAND[6] + d.timedelta(1): w = {"months": 6, "plus": True, "note": f"Open through {fmt(L)}"}
    elif F and not L:
        w = {"range": [n for n, t in CAND.items() if t < F], "note": f"Next season not released yet (from {fmt(F)})"}
    if w: res[eid] = w
js = ("/* Booking windows read from each campground's Recreation.gov availability calendar on " + day + ".\n"
      "   Generated by tools/booking_windows.py; do not edit by hand. months/days = measured window; range = only bounds known;\n"
      "   fcfs = every night not reservable. Applied by data/federal.js. */\n"
      "window.RECGOV_WINDOWS_CHECKED = " + json.dumps(day) + ";\nwindow.RECGOV_WINDOWS = " + json.dumps(res, separators=(",", ":")) + ";\n")
open(out, "w").write(js)
import collections
print(len(res), collections.Counter(("fcfs" if v.get("fcfs") else "months %s%s" % (v["months"], "+" if v.get("plus") else "") if "months" in v else "days %s" % v["days"] if "days" in v else "through" if "through" in v else "range") for v in res.values()).most_common())
