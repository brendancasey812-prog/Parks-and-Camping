# Turn tools/classify_releases.py output into data/windows.js (how each Recreation.gov campground releases nights).
#   python3 -I tools/release_rules.py <classes.json> data/windows.js <first reading YYYY-MM-DD> <second reading YYYY-MM-DD>
import json, sys, datetime as d, collections
src, out, day1, day2 = sys.argv[1:5]
C = json.load(open(src))
fmt = lambda s: d.date.fromisoformat(s).strftime("%m/%d/%Y")
W = {}
for k, c in C.items():
    cls = c["cls"]
    if cls == "rolling" and isinstance(c.get("months"), int):
        n = c["months"]
        W[k] = {"months": n, "note": f"Rolling {n} month{'s' if n > 1 else ''}, a new night every day: the booking calendar's edge moved forward day by day between {day1} and {day2}"}
    elif cls == "block" and not c.get("through"):
        W[k] = {"block": "", "note": f"Released in blocks: nothing of next season is open yet (from {fmt(c['F2'])}), though a 6-month window would already include it; the release date is not published"}
    elif cls == "block":
        W[k] = {"block": c["through"], "note": f"Released in a block: open through {fmt(c['through'])}; the edge did not move between {day1} and {day2}, and the next block's date is not published"}
    elif cls == "season":
        W[k] = {"block": c["through"], "season": True, "note": f"The whole coming season is already open (through {fmt(c['through'])}); when the following season releases cannot be seen yet"}
    elif cls == "upcoming":
        W[k] = {"upcoming": c["first"], "note": f"Next season (from {fmt(c['first'])}) not released yet; consistent with the 6-month window, confirmable once it is"}
    elif cls == "fcfs":
        W[k] = {"fcfs": True, "note": "Every night is listed as not reservable on Recreation.gov"}
js = ("/* How each Recreation.gov campground releases nights, read from its booking calendar on " + day1 + " and " + day2 + ".\n"
      "   Generated by tools/classify_releases.py + tools/release_rules.py; do not edit by hand.\n"
      "   months = rolling window (a new night each day at 5:00 AM Pacific, measured 11/18/2026); block = nights through that date are open and the next\n"
      "   release is not published; upcoming = not measurable yet (6-month default kept, marked assumed); fcfs = not reservable. */\n"
      "window.RECGOV_WINDOWS_CHECKED = " + json.dumps(day2) + ";\nwindow.RECGOV_WINDOWS = " + json.dumps(W, separators=(",", ":")) + ";\n"
      "(function () {\n"
      "  const W = window.RECGOV_WINDOWS || {}, day = window.RECGOV_WINDOWS_CHECKED;\n"
      "  window.SITES.forEach(s => {\n"
      "    if (!s.id.startsWith(\"rg-\")) {                          // hand-checked rows: never changed here, only confirmed when the calendar agrees\n"
      "      const w = s.rg && W[s.rg];\n"
      "      if (w && w.months && s.rule.kind === \"rolling\" && s.rule.months === w.months) { s.check = s.check.filter(c => c !== \"rule\"); s.sources = [{ t: \"Recreation.gov booking calendar (read \" + day + \"): \" + w.note, u: \"https://www.recreation.gov/camping/campgrounds/\" + s.rg }].concat(s.sources); }\n"
      "      return;\n"
      "    }\n"
      "    const w = W[s.rg]; if (!w) return;\n"
      "    const src = { t: \"Recreation.gov booking calendar (read \" + day + \"): \" + w.note, u: \"https://www.recreation.gov/camping/campgrounds/\" + s.rg };\n"
      "    const drop = k => { s.check = s.check.filter(c => c !== k); };\n"
      "    if (w.fcfs) { s.system = \"fcfs\"; s.rule = { kind: \"none\" }; s.walkup = \"only\"; s.walkupNote = \"First-come, first-served: every night is listed as not reservable on Recreation.gov\"; drop(\"rule\"); drop(\"walkup\"); }\n"
      "    else if (w.months) { s.rule = { kind: \"rolling\", months: w.months, time: \"05:00\" }; drop(\"rule\"); }\n"
      "    else if (\"block\" in w) { s.rule = { kind: \"block\", through: w.block || null, season: !!w.season }; drop(\"rule\"); }\n"
      "    s.sources = [src].concat(s.sources);\n"
      "  });\n"
      "})();\n")
open(out, "w").write(js)
print(len(W), collections.Counter(("months %d" % v["months"]) if "months" in v else ("season" if v.get("season") else "block") if "block" in v else "upcoming" if "upcoming" in v else "fcfs" for v in W.values()).most_common())
